def doc_for(word):
    """(signature, description) for a word, or None."""
    if word in BUILTIN_DOCS:
        return BUILTIN_DOCS[word]
    if word in SPECIAL_DOCS:
        return SPECIAL_DOCS[word]
    if word in OBJECT_DOCS:
        return (word, OBJECT_DOCS[word])
    if word in KEYWORD_HINTS:
        return (word, KEYWORD_HINTS[word])
    return None
